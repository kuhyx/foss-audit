#!/usr/bin/env python3
"""Write the NDK files that Google generates at NDK build time.

The NDK source tree (AOSP platform/ndk) carries meta/abis.json and
meta/platforms.json; its release build derives build/cmake/{abis,platforms,
system_libs,compiler_id}.cmake and meta/system_libs.json from them. This
does the same for a FOSS NDK, from the stub libraries actually built.

Usage: foss_android_ndk_meta.py <ndk-dir> <clang-version> <lib.so:min-api>...
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# The NDK release build adds each ABI's lowest OS version to abis.json;
# riscv64 is the one ABI whose minimum is above the platform minimum.
MIN_OS_OVERRIDES = {"riscv64": 35}


def add_min_os_versions(abis: dict[str, dict[str, object]], min_level: int) -> None:
    """Fill `min_os_version` the way the NDK release build does (in place)."""
    for abi, details in abis.items():
        details.setdefault("min_os_version", MIN_OS_OVERRIDES.get(abi, min_level))


def cmake_set(name: str, value: object) -> str:
    """One `set(NAME "value")` line; lists join with ';' as CMake expects."""
    if isinstance(value, list):
        value = ";".join(str(v) for v in value)
    return f'set({name} "{value}")'


def abis_cmake(abis: dict[str, dict[str, object]]) -> list[str]:
    """build/cmake/abis.cmake from meta/abis.json."""

    def known(bits: int | None) -> list[str]:
        return sorted(a for a, d in abis.items() if bits is None or d["bitness"] == bits)

    lines = [
        cmake_set("NDK_DEFAULT_ABIS", sorted(a for a, d in abis.items() if d["default"])),
        cmake_set("NDK_DEPRECATED_ABIS", sorted(a for a, d in abis.items() if d["deprecated"])),
        cmake_set("NDK_KNOWN_DEVICE_ABI32S", known(32)),
        cmake_set("NDK_KNOWN_DEVICE_ABI64S", known(64)),
        cmake_set("NDK_KNOWN_DEVICE_ABIS", known(None)),
    ]
    for abi, d in abis.items():
        lines += [
            cmake_set(f"NDK_ABI_{abi}_PROC", d["proc"]),
            cmake_set(f"NDK_ABI_{abi}_ARCH", d["arch"]),
            cmake_set(f"NDK_ABI_{abi}_TRIPLE", d["triple"]),
            cmake_set(f"NDK_ABI_{abi}_LLVM_TRIPLE", d["llvm_triple"]),
            cmake_set(f"NDK_ABI_{abi}_MIN_OS_VERSION", d["min_os_version"]),
            cmake_set(f"NDK_PROC_{d['proc']}_ABI", abi),
            cmake_set(f"NDK_ARCH_{d['arch']}_ABI", abi),
        ]
    return lines


def platforms_cmake(platforms: dict[str, object]) -> list[str]:
    """build/cmake/platforms.cmake from meta/platforms.json."""
    aliases: dict[str, int] = platforms["aliases"]  # type: ignore[assignment]
    lines = [
        cmake_set("NDK_MIN_PLATFORM_LEVEL", platforms["min"]),
        cmake_set("NDK_MAX_PLATFORM_LEVEL", platforms["max"]),
    ]
    lines += [cmake_set(f"NDK_PLATFORM_ALIAS_{k}", f"android-{v}") for k, v in aliases.items()]
    return lines


def main(argv: list[str]) -> int:
    """Write every generated file; argv = ndk dir, clang version, lib:api pairs."""
    ndk, version, pairs = Path(argv[1]), argv[2], argv[3:]
    libs = dict(p.split(":", 1) for p in pairs)
    meta, cmake = ndk / "meta", ndk / "build" / "cmake"
    abis = json.loads((meta / "abis.json").read_text())
    platforms = json.loads((meta / "platforms.json").read_text())
    add_min_os_versions(abis, int(platforms["min"]))
    (meta / "abis.json").write_text(json.dumps(abis, indent=2) + "\n")
    (meta / "system_libs.json").write_text(json.dumps(libs, indent=2, sort_keys=True) + "\n")
    outputs = {
        "abis.cmake": abis_cmake(abis),
        "platforms.cmake": platforms_cmake(platforms),
        "system_libs.cmake": [cmake_set("NDK_SYSTEM_LIBS", sorted(libs))],
        "compiler_id.cmake": [
            f"set(CMAKE_{lang}_COMPILER_VERSION {version})" for lang in ("ASM", "C", "CXX")
        ],
    }
    for name, lines in outputs.items():
        (cmake / name).write_text("# Generated by foss_android_ndk_meta.py.\n" + "\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
